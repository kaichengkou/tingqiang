import {chromium} from './harness.mjs';
import assert from 'node:assert/strict';
import {writeFile, mkdtemp} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {execFileSync} from 'node:child_process';
import {encodeWav} from '../dist/lib/analysis.mjs';

const output = process.env.TINGQIANG_TEST_OUTPUT || await mkdtemp(join(tmpdir(), 'tingqiang-browser-'));
const browser = await chromium.launch({executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', headless: true, args: ['--no-sandbox', '--autoplay-policy=no-user-gesture-required']});
const page = await browser.newPage({viewport: {width: 1440, height: 1100}, deviceScaleFactor: 1});
const errors = [];
page.on('pageerror', error => errors.push(error.message));
try {
  await page.goto(process.env.TINGQIANG_TEST_URL || 'http://127.0.0.1:8000/');
  await page.screenshot({path: join(output, 'tingqiang-empty.png'), fullPage: true});
  await page.locator('#demo-button').click();
  await page.waitForFunction(() => document.getElementById('analysis-status').textContent.includes('分析完成'));
  assert.equal(await page.locator('#curve-source').textContent(), '人声分析');
  await page.screenshot({path: join(output, 'tingqiang-desktop.png'), fullPage: true});
  await page.locator('#play-button').click();
  await page.waitForFunction(() => document.getElementById('audio').currentTime > 0.3);
  await page.locator('#play-button').click();
  await page.locator('#rate').selectOption('0.65');
  assert.equal(await page.locator('#audio').evaluate(a => a.preservesPitch), true);
  assert.equal(await page.locator('#audio').evaluate(a => a.playbackRate), 0.65);
  await page.locator('#overview').click({position: {x: 300, y: 20}});
  const before = await page.locator('#audio').evaluate(a => a.currentTime);
  await page.locator('[data-mode="accompaniment"]').click();
  const after = await page.locator('#audio').evaluate(a => a.currentTime);
  assert.ok(Math.abs(before - after) < 0.15, `stem switch moved ${before} -> ${after}`);
  await page.locator('#set-a').click();
  await page.locator('#forward-button').click();
  await page.locator('#set-b').click();
  assert.equal(await page.locator('#loop-button').getAttribute('aria-pressed'), 'true');
  await page.locator('#play-button').click();
  await page.waitForFunction(() => !document.getElementById('audio').paused);
  await page.locator('#play-button').click();
  await page.locator('#clear-loop').click();
  assert.equal(await page.locator('#a-time').textContent(), '—');
  const box = await page.locator('#pitch-chart').boundingBox();
  await page.mouse.move(box.x + 180, box.y + 100); await page.mouse.down();
  await page.mouse.move(box.x + 340, box.y + 100, {steps: 8}); await page.mouse.up();
  assert.equal(await page.locator('#loop-button').getAttribute('aria-pressed'), 'true');

  const samples = Float32Array.from({length: 12000 * 5}, (_, i) => 0.3 * Math.sin(2 * Math.PI * 440 * i / 12000));
  await writeFile(join(output, 'tingqiang-tone.wav'), Buffer.from(encodeWav([samples], 12000)));
  execFileSync('ffmpeg', ['-v', 'error', '-y', '-i', join(output, 'tingqiang-tone.wav'), join(output, 'tingqiang-tone.mp3')]);
  await page.locator('#audio-input').setInputFiles(join(output, 'tingqiang-tone.mp3'));
  await page.waitForFunction(() => document.getElementById('filename').textContent === 'tingqiang-tone');
  assert.equal(await page.locator('#a-time').textContent(), '—');
  await page.waitForFunction(() => document.getElementById('analysis-status').textContent.includes('分析完成'));
  assert.equal(await page.locator('#curve-source').textContent(), '原录音分析');
  const redPixels = await page.locator('#pitch-chart').evaluate(c => {
    const pixels = c.getContext('2d').getImageData(0, 0, c.width, c.height).data; let n = 0;
    for (let i = 0; i < pixels.length; i += 4) if (pixels[i] > 120 && pixels[i] > pixels[i + 1] * 1.5 && pixels[i + 1] < 130) n++;
    return n;
  });
  assert.ok(redPixels > 100, 'no pitch trace was drawn');
  await page.locator('#lyrics-input').setInputFiles({name: 'test.lrc', mimeType: 'text/plain', buffer: Buffer.from('[00:00.00]<00:00.00>看<00:01.00>腔\n[00:02.00]第二句\n[00:04.00]<img src=x onerror=alert(1)>')});
  assert.equal(await page.locator('.lyric-row').count(), 3);
  assert.equal(await page.locator('.lyric-text img').count(), 0);
  await page.locator('.lyric-text').nth(1).click();
  assert.ok(Math.abs(await page.locator('#audio').evaluate(a => a.currentTime) - 2) < 0.15);
  await page.locator('#lyrics-input').setInputFiles({name: 'test.txt', mimeType: 'text/plain', buffer: Buffer.from('第一句\n第二句')});
  assert.equal(await page.locator('.lyric-time').first().textContent(), '待标记');
  await page.locator('.stamp-button').first().click();
  assert.notEqual(await page.locator('.lyric-time').first().textContent(), '待标记');
  await page.locator('#settings-button').click();
  await page.locator('#edit-bpm').click();
  await page.locator('#bpm-input').fill('100'); await page.locator('#beat-offset').fill('0'); await page.locator('#save-bpm').click();
  assert.equal(await page.locator('#bpm-label').textContent(), '手动 100 BPM');

  await page.setViewportSize({width: 390, height: 844});
  await page.locator('#audio-input').setInputFiles(join(output, 'tingqiang-tone.mp3'));
  await page.waitForFunction(() => document.getElementById('analysis-status').textContent.includes('分析完成') && !document.getElementById('lyrics-list').querySelector('.lyric-row'));
  const sizes = await page.evaluate(() => ({w: window.innerWidth, scroll: document.documentElement.scrollWidth}));
  assert.ok(sizes.scroll <= sizes.w + 1, `mobile overflow ${JSON.stringify(sizes)}`);
  await page.screenshot({path: join(output, 'tingqiang-mobile.png'), fullPage: true});
  assert.deepEqual(errors, []);
  console.log('Browser checks passed: real MP3 decode, pitch drawing, playback/stem switch, pitch-preserving speed, AB/drag loops, safe lyric parsing/timing, beat override, mobile layout.');
} finally { await browser.close(); }
